#!/usr/bin/env node
// Per-file size guard (modeled on cozys.market's pre-commit). Blocks a commit when a staged
// source file is over MAX_BYTES (~20KB, about 5k tokens), so files stay small enough to review
// and edit safely. Files that were already over the limit are grandfathered in
// .githooks/size-baseline.json and may grow at most GROWTH over their recorded size; split them
// to shrink them, never raise the number without a reason.
//   node scripts/check-file-sizes.mjs            -> checks staged files (pre-commit)
//   node scripts/check-file-sizes.mjs --all      -> checks every tracked file (npm test)
import { execFileSync } from 'node:child_process';
import { readFileSync, statSync } from 'node:fs';

export const MAX_BYTES = 20_000;
export const GROWTH = 1.1;
export const IGNORE = [
  /(^|\/)package-lock\.json$/, /^dist\//, /^node_modules\//, /^\.astro\//, /\.min\./, /\.map$/,
  /\.(png|jpe?g|gif|webp|avif|ico|svg|mp4|webm|mov|mp3|wav|woff2?|ttf|otf|pdf|zip|gz|tar|xlsx|ai|psd|db|sqlite)$/i,
  /^public\/textmode\.umd\.js$/, // vendored third-party bundle
  /^src\/data\/image-manifest\.json$/, // generated by scripts/optimize-inventory.mjs
];
const baseline = JSON.parse(readFileSync(new URL('../.githooks/size-baseline.json', import.meta.url), 'utf8'));

export function limitFor(path) {
  return baseline[path] ? Math.ceil(baseline[path] * GROWTH) : MAX_BYTES;
}

export function check(files, sizeOf) {
  const out = [];
  for (const f of files) {
    if (IGNORE.some((re) => re.test(f))) continue;
    const bytes = sizeOf(f);
    if (bytes > limitFor(f)) out.push({ file: f, bytes, limit: limitFor(f) });
  }
  return out;
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop());
if (isMain) {
  const all = process.argv.includes('--all');
  const git = (...a) => execFileSync('git', a, { encoding: 'utf8' });
  const files = (all ? git('ls-files', '-z') : git('diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z')).split('\0').filter(Boolean);
  const sizeOf = all ? (f) => { try { return statSync(f).size; } catch { return 0; } } : (f) => Number(git('cat-file', '-s', `:${f}`).trim());
  const bad = check(files, sizeOf);
  if (bad.length) {
    console.error(`File size guard: ${bad.length} file(s) over the limit (new files: ${MAX_BYTES} bytes; grandfathered: baseline x${GROWTH}):`);
    for (const b of bad) console.error(`  ${b.file}  ${b.bytes} bytes (limit ${b.limit})`);
    console.error('\nFix: split the file by responsibility (move data/config/components into their own modules). Do not bypass with --no-verify.');
    process.exit(1);
  }
}
